"""`lumiere adopt` - put a HyperFrames project's timing under Lumiere.

Lumiere does not create video projects and does not choose what kind they are.
HyperFrames scaffolds them and its workflows decide the shape - explainer,
product launch, slideshow, recut. What varies between those is the composition;
what does not vary is that timed elements carry `data-start` and `data-duration`,
which is the whole of what Lumiere overrides.

So adoption is one thing: a note in the project's own instructions saying
that seconds here are derived. Where the narration and its words live is the
project's choice, named in its markup. The how-to lives in the `lumiere`
skill, which `lumiere skills update` installs into the project.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

#: The heading we own in the project's AGENTS.md. Matching on it is how
#: adoption stays idempotent.
LUMIERE_SECTION = "## Timing comes from the recording (Lumiere)"

NOTE = f"""
{LUMIERE_SECTION}

This project's timing is **derived from a recorded narration**, not written by
hand. Do not type a value into `data-start`, `data-duration`, or a GSAP position
- they are build artifacts, regenerated by `lumiere build`. `lumiere check`
warns about a typed second and fails when the seconds are stale or an anchor
cannot be honoured.

Say *when* instead, and let the build resolve it:

```html
<div id="harbor-tile" data-lumiere-start="word:Harbor#2" data-lumiere-end="word:fine.end+0.2">
```

The grammar, the loop, and the mistakes worth not repeating are in the
`lumiere` skill (`.agents/skills/lumiere/`, installed by `lumiere skills
update`). Invoke it before changing timing.
"""

MARKERS = ("hyperframes.json", "index.html")


@dataclass(frozen=True)
class AdoptReport:
    """What adoption changed."""

    project: Path
    instructed: tuple[str, ...]


def adopt(project: Path) -> AdoptReport:
    """Add Lumiere's timing spine to an existing HyperFrames project."""
    missing = [name for name in MARKERS if not (project / name).exists()]
    if missing:
        raise ValueError(
            f"{project} is not a HyperFrames project (no {', '.join(missing)}). "
            f"Create one first with `hyperframes init`, choosing the workflow "
            f"that fits the video, then adopt it."
        )

    # Append to the agent instructions the project already has, rather than
    # shipping a competing file that would never be read. `AGENTS.md` is the
    # one file every agent reads; a `CLAUDE.md` is not created or edited.
    instructed = []
    path = project / "AGENTS.md"
    if path.exists() and not path.is_symlink():
        text = path.read_text()
        if LUMIERE_SECTION not in text:
            path.write_text(text.rstrip() + "\n" + NOTE)
            instructed.append(path.name)

    return AdoptReport(project=project, instructed=tuple(instructed))
